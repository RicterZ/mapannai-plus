// All API traffic is intercepted into an isolated SQLite database; images are fixture-only.
import assert from 'node:assert/strict'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { NextRequest } from 'next/server'
const { chromium } = require('playwright')

async function main() {
    const directory = mkdtempSync(path.join(tmpdir(), 'mapannai-note-browser-'))
    process.env.SQLITE_PATH = path.join(directory, 'test.db')
    const { upsertTrip, setTripMarker, getAllTrips, getAllTripDays } = await import('../src/lib/db/trip-service')
    const { upsertMarker, getAllMarkers } = await import('../src/lib/db/marker-service')
    const { getTripMarkerNote, updateTripMarkerNote } = await import('../src/lib/db/trip-marker-note-service')
    const handlers = await import('../src/app/api/trips/[id]/markers/[markerId]/note/route')
    const { getDb } = await import('../src/lib/db')
    const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
    try {
        const now = new Date().toISOString()
        for (const [id, date] of [['ba', '2027-01-23'], ['ff14', '2026-10-31']]) upsertTrip({ id, name: id === 'ba' ? 'BA旅行' : 'FF14旅行', startDate: date, endDate: date, createdAt: now, updatedAt: now })
        upsertMarker('venue', 140.035, 35.647, { title: '幕张展览馆', markdownContent: '<p>通用入口攻略</p>', headerImage: 'https://images.example/shared.jpg' })
        setTripMarker('ba', 'venue', true)
        updateTripMarkerNote('ba', 'venue', { content: '<p>BA活动</p>', headerImage: 'https://images.example/ba.jpg' })
        updateTripMarkerNote('ff14', 'venue', { content: '<p>FF14活动</p>', headerImage: 'https://images.example/ff14.jpg' })
        const errors: string[] = []
        for (const mobile of [false, true]) {
            const context = await browser.newContext({ reducedMotion: 'reduce', viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1050 }, isMobile: mobile, hasTouch: mobile })
            const page = await context.newPage()
            console.log('Selection browser', { mobile })
            await page.addInitScript(() => { localStorage.setItem('mapViewState', JSON.stringify({ longitude: 140.035, latitude: 35.647, zoom: 14 })); localStorage.setItem('addMarkerEnabled', 'false') })
            page.setDefaultTimeout(15000)
            page.on('pageerror', (error: Error) => errors.push(error.message))
            await page.route('https://images.example/**', (route: any) => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="160" height="90"><rect width="160" height="90" fill="#c5d9e8"/></svg>' }))
            await page.route('**/api/**', async (route: any) => {
                const request = route.request(), url = new URL(request.url()), method = request.method()
                if (method === 'GET' && url.pathname === '/api/markers') return route.fulfill({ json: [] })
                if (method === 'GET' && url.pathname === '/api/dataset') return route.fulfill({ json: { success: true, data: getAllMarkers() } })
                if (method === 'GET' && url.pathname === '/api/trips') return route.fulfill({ json: getAllTrips().map(trip => ({ ...trip, days: getAllTripDays().filter(day => day.tripId === trip.id) })) })
                if (/^\/api\/trips\/(ba|ff14)\/markers\/venue\/note$/.test(url.pathname) && method === 'PATCH') {
                    const response = await handlers.PATCH(new NextRequest(url, { method, body: request.postData() }), { params: { id: url.pathname.split('/')[3], markerId: 'venue' } })
                    return route.fulfill({ status: response.status, body: await response.text(), contentType: 'application/json' })
                }
                return route.fulfill({ status: 400, json: { error: 'Unexpected fixture request' } })
            })
            await page.goto(`${process.env.REVIEW_BASE_URL || 'http://127.0.0.1:3108'}/`, { waitUntil: 'domcontentloaded' })
            if (mobile) await page.getByRole('button', { name: '展开 MapAnNai 侧栏' }).click()
            await page.getByRole('switch', { name: '编辑模式', checked: false }).waitFor()
            await page.locator('.left-sidebar').getByText('BA旅行', { exact: true }).click()
            await page.locator('.journey-pending-place > button.flex-1').click()
            const popup = page.locator('.app-popup')
            assert.equal(await popup.getByAltText('幕张展览馆封面').getAttribute('src'), 'https://images.example/ba.jpg')
            await popup.getByRole('button', { name: '查看', exact: true }).click()
            console.log('Opened detail', { mobile })
            const sidebar = page.locator('.right-sidebar')
            assert.equal(await sidebar.getByText('旅行笔记', { exact: true }).count(), 0)
            assert.equal(await sidebar.locator('.lucide-check, .lucide-notebook-pen').count(), 0)
            await sidebar.getByRole('button', { name: '编辑地点', exact: true }).click()
            await page.getByRole('dialog', { name: '编辑地点', exact: true }).waitFor()
            await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click()
            if (!mobile) {
                const toggle = page.getByRole('switch', { name: '编辑模式' })
                for (const checked of ['true', 'false']) {
                    await toggle.click()
                    assert.equal(await toggle.getAttribute('aria-checked'), checked)
                    await sidebar.getByRole('button', { name: '编辑地点', exact: true }).waitFor()
                    assert.equal(await sidebar.getByRole('button', { name: 'BA旅行', exact: true }).getAttribute('aria-pressed'), 'true')
                }
            }
            await sidebar.getByRole('region', { name: '本次旅行笔记' }).getByText('BA活动', { exact: true }).waitFor()
            assert.equal(await sidebar.getByRole('region', { name: '地点通用笔记' }).count(), 0)
            assert.equal(await sidebar.getByRole('button', { name: /编辑本次|添加本次|编辑通用|复制通用|加入当天|加入旅行/ }).count(), 0)
            const bubble = sidebar.getByRole('button', { name: 'FF14旅行', exact: true })
            // Click padding, the exact region that was previously unresponsive.
            const box = await bubble.boundingBox(); assert(box)
            await bubble.click({ position: { x: box.width - 8, y: box.height - 8 } })
            assert.equal(await bubble.getAttribute('aria-pressed'), 'true')
            await sidebar.getByText('FF14活动', { exact: true }).waitFor()
            assert.equal(await sidebar.getByAltText('FF14旅行封面').getAttribute('src'), 'https://images.example/ff14.jpg')
            assert.equal(await sidebar.getByAltText('幕张展览馆封面').count(), 0, 'trip covers live inside membership bubbles')
            await bubble.click()
            await sidebar.getByRole('region', { name: '地点通用笔记' }).getByText('通用入口攻略', { exact: true }).waitFor()
            assert.equal(await bubble.getAttribute('aria-pressed'), 'false')
            assert.equal(await sidebar.getByRole('region', { name: '本次旅行笔记' }).count(), 0)
            await sidebar.getByRole('button', { name: '编辑地点', exact: true }).click()
            const editor = page.getByRole('dialog', { name: '编辑地点', exact: true })
            assert.equal(await editor.getByRole('button', { name: '通用资料', exact: true }).getAttribute('aria-pressed'), 'true')
            await editor.getByRole('button', { name: 'FF14旅行', exact: true }).click()
            assert.equal(await editor.getByAltText('地点封面').getAttribute('src'), 'https://images.example/ff14.jpg')
            await editor.getByPlaceholder('幕张展览馆').fill('FF14新标题')
            await editor.getByRole('button', { name: '移除', exact: true }).click()
            await editor.getByRole('button', { name: 'BA旅行', exact: true }).click()
            assert.equal(await editor.getByAltText('地点封面').getAttribute('src'), 'https://images.example/ba.jpg')
            await editor.getByRole('button', { name: 'FF14旅行', exact: true }).click()
            assert.equal(await editor.getByAltText('地点封面').count(), 0, 'cover drafts are independent')
            await editor.getByRole('button', { name: '保存旅行笔记', exact: true }).click()
            await page.getByText('旅行笔记已保存', { exact: true }).waitFor()
            assert.equal(getTripMarkerNote('ff14', 'venue')!.headerImage, null)
            assert.equal(getTripMarkerNote('ba', 'venue')!.headerImage, 'https://images.example/ba.jpg')
            await editor.getByRole('button', { name: '关闭', exact: true }).click()
            await sidebar.getByRole('button', { name: '返回地图' }).click()
            if (mobile && await page.getByRole('button', { name: '展开 MapAnNai 侧栏' }).isVisible()) await page.getByRole('button', { name: '展开 MapAnNai 侧栏' }).click()
            const returnStarted = Date.now()
            await page.getByRole('button', { name: '返回全览' }).click()
            await page.locator('.journey-overview').waitFor()
            assert.equal(new URL(page.url()).hash, '', 'return updates navigation immediately')
            console.log('Overview returned', { mobile, milliseconds: Date.now() - returnStarted })
            if (mobile) await page.getByRole('button', { name: '返回地图（收起侧栏）', exact: true }).click()
            await page.locator('.map-marker').first().click()
            assert.equal(await popup.getByAltText('幕张展览馆封面').getAttribute('src'), 'https://images.example/ba.jpg', 'overview popup uses latest trip photo')
            await popup.getByRole('button', { name: '查看', exact: true }).click()
            console.log('Opened detail', { mobile })
            await sidebar.getByRole('region', { name: '地点通用笔记' }).waitFor()
            assert.equal(await sidebar.getByRole('button', { pressed: true }).count(), 0, 'overview defaults to no selected travel note')
            await page.waitForFunction(() => { const panel = document.querySelector('.right-sidebar'); if (!panel) return false; const rect = panel.getBoundingClientRect(); return Math.abs(rect.right - innerWidth) < 1 && rect.width > 0 })
            await page.screenshot({ path: path.join(tmpdir(), `stud121-selection-${mobile ? 'mobile' : 'desktop'}.png`), fullPage: true })
            await context.close()
            updateTripMarkerNote('ff14', 'venue', { title: '', headerImage: 'https://images.example/ff14.jpg' })
        }
        assert.deepEqual(errors, [])
        console.log('Desktop/mobile selection checks passed: padding clicks, toggle to shared, no display actions, scoped cover drafts, correct popup images and overview defaults.')
    } finally { await browser.close(); getDb().close(); rmSync(directory, { recursive: true, force: true }) }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
